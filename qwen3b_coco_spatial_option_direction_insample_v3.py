"""
Qwen2.5-VL-3B + COCO random-map layer-wise readout.

This version intentionally uses the SAME full sample set to define and evaluate
the readout directions. It is a descriptive in-sample representation analysis,
not a held-out probe-generalization experiment.

At each decoder layer and for each carrier separately:

Spatial directions
------------------
For r in {left, right, above, below}:

    mu_r,l = mean_i q_i,l  over all samples with relation r
    mu_l   = (1/4) sum_r mu_r,l
    d_r,l  = unit(mu_r,l - mu_l)

Prediction:

    r_hat_i,l = argmax_r cos(q_i,l - mu_l, d_r,l)

Option directions
-----------------
For c in {A, B, C, D}, using the option ACTUALLY GENERATED by the model:

    nu_c,l = mean_i q_i,l  over all samples with generated option c
    nu_l   = (1/4) sum_c nu_c,l
    e_c,l  = unit(nu_c,l - nu_l)

Prediction:

    c_hat_i,l = argmax_c cos(q_i,l - nu_l, e_c,l)

Two candidate carriers are evaluated independently:

    object-pair:
      q_obj,l =
        (h_real[sub] - h_real[ref])
        - (h_gray[sub] - h_gray[ref])

    prompt-final:
      q_last,l =
        h_real[last] - h_gray[last]

The plotted curves are layer-level maxima:

    Spatial Readout(l)
      = max(
          relation accuracy from q_obj,l,
          relation accuracy from q_last,l
        )

    Option Readout(l)
      = max(
          generated-option accuracy from q_obj,l,
          generated-option accuracy from q_last,l
        )

The max is over aggregate layer-level accuracy, never per-example oracle choice.

Both readouts use:
  - the same samples,
  - the same image,
  - the same randomized relation -> A/B/C/D question,
  - the same forward states.

Main output:
    spatial_option_readout_insample.png

Additional audit outputs:
    layerwise_readout_insample.csv
    generation.csv
    direction_metadata.json
    metadata.json

Run from the AdaptVis llava16 repository root.

Full run
--------
CUDA_VISIBLE_DEVICES=0 PYTHONUNBUFFERED=1 \
python -u qwen3b_coco_spatial_option_direction_insample_v3.py \
  --max-samples 0 \
  --output-dir output/qwen3b_coco_spatial_option_direction_insample_v3 \
  --overwrite

Quick run
---------
CUDA_VISIBLE_DEVICES=0 PYTHONUNBUFFERED=1 \
python -u qwen3b_coco_spatial_option_direction_insample_v3.py \
  --max-samples 160 \
  --output-dir output/qwen3b_coco_spatial_option_direction_insample_quick \
  --overwrite
"""

