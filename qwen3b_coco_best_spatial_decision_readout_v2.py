"""
Qwen2.5-VL-3B + COCO random-map analysis.

At every decoder layer, build TWO carrier-agnostic readouts:

    Spatial Readout(l)
      = max(
          relation readout from object-pair text state,
          relation readout from prompt-final state
        )

    Option Readout(l)
      = max(
          generated-option readout from object-pair text state,
          generated-option readout from prompt-final state
        )

The max is taken at the LAYER-LEVEL over held-out aggregate readout accuracy.
It is NOT a per-sample oracle.

Both readouts come from the same samples, the same randomized A/B/C/D question,
and the same Real-Gray forward states.

Spatial labels:
    left / right / above / below

Option labels:
    the A/B/C/D option ACTUALLY GENERATED by the model

No GT-option readout is plotted.

Outputs:
    spatial_option_readout_all.png
    spatial_option_readout_correct.png

Main plot styling is intentionally minimal:
    x-axis: Decoder Layer
    y-axis: Readout Accuracy
    legend: Spatial Readout / Option Readout
    no chance line
    no extra title

Run from the AdaptVis llava16 repository root.

Full run:
CUDA_VISIBLE_DEVICES=0 PYTHONUNBUFFERED=1 \
python -u qwen3b_coco_best_spatial_decision_readout_v2.py \
  --max-samples 0 \
  --eval-max-samples 0 \
  --output-dir output/qwen3b_coco_best_spatial_decision_readout_v2 \
  --overwrite

Quick run:
CUDA_VISIBLE_DEVICES=0 PYTHONUNBUFFERED=1 \
python -u qwen3b_coco_best_spatial_decision_readout_v2.py \
  --max-samples 160 \
  --eval-max-samples 80 \
  --output-dir output/qwen3b_coco_best_spatial_decision_readout_quick \
  --overwrite
"""

