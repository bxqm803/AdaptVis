def collect_scan_arrays(
    *,
    source_dir: Path,
    rows: Sequence[Mapping[str, Any]],
    selected_layers: Sequence[int],
) -> Dict[str, Any]:
    if not rows:
        raise RuntimeError("No scan rows")

    first = load_cache(cache_path(source_dir, int(rows[0]["sid"])))
    source_layers = list(map(int, first["layers"].tolist()))
    source_lookup = {layer: index for index, layer in enumerate(source_layers)}
    missing = sorted(set(selected_layers) - set(source_lookup))
    if missing:
        raise RuntimeError(f"Layers missing from source caches: {missing}")

    layer_indices = [source_lookup[int(layer)] for layer in selected_layers]
    labels: List[int] = []
    folds: List[int] = []
    statuses: List[str] = []
    sids: List[int] = []
    head_visual: List[np.ndarray] = []
    qk_pred: List[np.ndarray] = []
    qk_margin: List[np.ndarray] = []
    visual_mass: List[np.ndarray] = []
    object_pair: List[np.ndarray] = []

    for row in tqdm(rows, desc="load-v3-producer-cache"):
        cache = load_cache(cache_path(source_dir, int(row["sid"])))
        labels.append(int(row["label"]))
        folds.append(int(row["fold"]))
        statuses.append(str(row["generation_pair_status"]))
        sids.append(int(row["sid"]))
        head_visual.append(
            np.asarray(cache["head_visual_pair_pre"])[layer_indices]
        )
        qk_pred.append(
            np.asarray(cache["attention_centroid_pred"])[layer_indices]
        )
        qk_margin.append(
            np.asarray(cache["attention_centroid_gt_margin"])[layer_indices]
        )
        visual_mass.append(
            np.asarray(cache["visual_attention_mass"])[layer_indices]
        )
        object_pair.append(
            np.asarray(cache["object_pair"])[layer_indices]
        )

    return {
        "layers": np.asarray(selected_layers, dtype=np.int64),
        "sids": np.asarray(sids, dtype=np.int64),
        "labels": np.asarray(labels, dtype=np.int64),
        "folds": np.asarray(folds, dtype=np.int64),
        "statuses": np.asarray(statuses, dtype=object),
        "head_visual_pair_pre": np.stack(head_visual, axis=0).astype(np.float32),
        "qk_pred": np.stack(qk_pred, axis=0).astype(np.int64),
        "qk_margin": np.stack(qk_margin, axis=0).astype(np.float32),
        "visual_mass": np.stack(visual_mass, axis=0).astype(np.float32),
        "object_pair": np.stack(object_pair, axis=0).astype(np.float32),
    }


def scan_producer_heads(
    *,
    args: argparse.Namespace,
    v3: Any,
    attention_helper: Any,
    decoder_layers: Sequence[Any],
    scan: Mapping[str, Any],
    output_dir: Path,
) -> Tuple[List[Dict[str, Any]], List[Dict[str, Any]]]:
    labels = np.asarray(scan["labels"], dtype=np.int64)
    folds = np.asarray(scan["folds"], dtype=np.int64)
    layers = np.asarray(scan["layers"], dtype=np.int64)
    head_visual = np.asarray(scan["head_visual_pair_pre"], dtype=np.float32)
    qk_pred = np.asarray(scan["qk_pred"], dtype=np.int64)
    qk_margin = np.asarray(scan["qk_margin"], dtype=np.float32)
    visual_mass = np.asarray(scan["visual_mass"], dtype=np.float32)
    object_pair = np.asarray(scan["object_pair"], dtype=np.float32)

    n_samples, n_selected_layers, n_heads, head_dim = head_visual.shape
    print(
        f"Producer scan: N={n_samples}, layers={layers.tolist()}, "
        f"heads={n_heads}, head_dim={head_dim}",
        flush=True,
    )

    object_pair_margins: Dict[int, np.ndarray] = {}
    for local_layer, layer in enumerate(layers.tolist()):
        _, margin, _ = v3.crossfit_centroids(
            object_pair[:, local_layer, :],
            labels,
            folds,
            args.centroid_metric,
        )
        object_pair_margins[int(layer)] = margin

    metrics: List[Dict[str, Any]] = []
    per_sample_store: Dict[Tuple[int, int], Dict[str, np.ndarray]] = {}

    for local_layer, layer in enumerate(layers.tolist()):
        attention = attention_helper.resolve_self_attention(
            decoder_layers[int(layer)]
        )
        o_weight_t = attention_helper.reshape_o_projection(
            attention,
            n_heads=n_heads,
            head_dim=head_dim,
        ).detach().float()  # [D,H,Dh], remains on model device
        grams = torch.einsum(
            "ohd,ohe->hde",
            o_weight_t,
            o_weight_t,
        ).detach().double().cpu().numpy()
        del o_weight_t

        x_layer = head_visual[:, local_layer, :, :].astype(np.float64)
        identity_grams = np.broadcast_to(
            np.eye(head_dim, dtype=np.float64)[None, :, :],
            (n_heads, head_dim, head_dim),
        )
        pre_pred_all, pre_margin_all = crossfit_metric_centroids_batched(
            x_layer,
            labels,
            folds,
            identity_grams,
            args.centroid_metric,
        )
        post_pred_all, post_margin_all = crossfit_metric_centroids_batched(
            x_layer,
            labels,
            folds,
            grams,
            args.centroid_metric,
        )
        norms_all = post_wo_norms_batched(x_layer, grams)

        for head in range(n_heads):
            pre_pred = pre_pred_all[:, head]
            pre_margin = pre_margin_all[:, head]
            post_pred = post_pred_all[:, head]
            post_margin = post_margin_all[:, head]
            norms = norms_all[:, head]

            qk_accuracy = float(
                np.mean(qk_pred[:, local_layer, head] == labels)
            )
            pre_accuracy = float(np.mean(pre_pred == labels))
            post_accuracy = float(np.mean(post_pred == labels))
            joint_min = float(min(qk_accuracy, post_accuracy))
            joint_geomean = float(
                math.sqrt(max(qk_accuracy, 0.0) * max(post_accuracy, 0.0))
            )

            metrics.append(
                {
                    "layer": int(layer),
                    "head": int(head),
                    "N": int(n_samples),
                    "qk_attention_centroid_accuracy": qk_accuracy,
                    "qk_attention_centroid_macro_accuracy": macro_accuracy(
                        qk_pred[:, local_layer, head],
                        labels,
                    ),
                    "qk_gt_margin_mean": safe_mean(
                        qk_margin[:, local_layer, head]
                    ),
                    "qk_gt_margin_positive_rate": safe_mean(
                        qk_margin[:, local_layer, head] > 0
                    ),
                    "visual_attention_mass_mean": safe_mean(
                        visual_mass[:, local_layer, head]
                    ),
                    "pre_ov_centroid_accuracy": pre_accuracy,
                    "pre_ov_centroid_macro_accuracy": macro_accuracy(
                        pre_pred,
                        labels,
                    ),
                    "pre_ov_gt_margin_mean": safe_mean(pre_margin),
                    "post_ov_centroid_accuracy": post_accuracy,
                    "post_ov_centroid_macro_accuracy": macro_accuracy(
                        post_pred,
                        labels,
                    ),
                    "post_ov_gt_margin_mean": safe_mean(post_margin),
                    "post_ov_write_norm_mean": safe_mean(norms),
                    "post_ov_write_norm_median": safe_median(norms),
                    "wo_accuracy_delta": float(post_accuracy - pre_accuracy),
                    "pre_vs_object_margin_corr": safe_corr(
                        pre_margin,
                        object_pair_margins[int(layer)],
                    ),
                    "post_vs_object_margin_corr": safe_corr(
                        post_margin,
                        object_pair_margins[int(layer)],
                    ),
                    "qk_vs_post_margin_corr": safe_corr(
                        qk_margin[:, local_layer, head],
                        post_margin,
                    ),
                    "joint_min": joint_min,
                    "joint_geomean": joint_geomean,
                }
            )
            per_sample_store[(int(layer), int(head))] = {
                "pre_margin": np.asarray(pre_margin, dtype=np.float32),
                "post_margin": np.asarray(post_margin, dtype=np.float32),
                "post_norm": np.asarray(norms, dtype=np.float32),
                "qk_margin": np.asarray(
                    qk_margin[:, local_layer, head],
                    dtype=np.float32,
                ),
            }

    write_csv(output_dir / "producer_head_metrics.csv", metrics)

    eligible = [
        row for row in metrics
        if float(row["visual_attention_mass_mean"]) >= args.min_visual_mass
    ]
    ranked = sorted(
        eligible,
        key=lambda row: (
            float(row[args.rank_metric]),
            float(row["post_ov_centroid_accuracy"]),
            float(row["qk_attention_centroid_accuracy"]),
        ),
        reverse=True,
    )
    top = ranked[: args.top_heads]
    top_rows: List[Dict[str, Any]] = []
    for rank, row in enumerate(top, start=1):
        item = dict(row)
        item["rank"] = rank
        top_rows.append(item)
    write_json(output_dir / "producer_top_heads.json", top_rows)

    if args.save_top_per_sample:
        per_sample_path = output_dir / "producer_top_per_sample.jsonl"
        per_sample_path.unlink(missing_ok=True)
        sids = np.asarray(scan["sids"], dtype=np.int64)
        for item in top_rows:
            layer = int(item["layer"])
            head = int(item["head"])
            values = per_sample_store[(layer, head)]
            for index, sid in enumerate(sids.tolist()):
                append_jsonl(
                    per_sample_path,
                    {
                        "rank": int(item["rank"]),
                        "layer": layer,
                        "head": head,
                        "sid": int(sid),
                        "gt": ID_TO_REL[int(labels[index])],
                        "fold": int(folds[index]),
                        "qk_margin": float(values["qk_margin"][index]),
                        "pre_ov_margin": float(values["pre_margin"][index]),
                        "post_ov_margin": float(values["post_margin"][index]),
                        "post_ov_write_norm": float(values["post_norm"][index]),
                    },
                )

    return metrics, top_rows


