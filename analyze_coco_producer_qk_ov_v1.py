def stratified_limit(
    rows: Sequence[Mapping[str, Any]],
    limit: Optional[int],
    seed: int,
) -> List[Dict[str, Any]]:
    rows = [dict(row) for row in rows]
    if limit is None or limit <= 0 or len(rows) <= limit:
        return sorted(rows, key=lambda item: int(item["sid"]))

    rng = random.Random(seed)
    groups: Dict[str, List[Dict[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[str(row["gt"])].append(row)
    for values in groups.values():
        rng.shuffle(values)

    ordered_labels = [relation for relation in RELATIONS if relation in groups]
    selected: List[Dict[str, Any]] = []
    cursors = {label: 0 for label in ordered_labels}
    while len(selected) < limit:
        progressed = False
        for label in ordered_labels:
            index = cursors[label]
            if index < len(groups[label]) and len(selected) < limit:
                selected.append(groups[label][index])
                cursors[label] += 1
                progressed = True
        if not progressed:
            break
    selected.sort(key=lambda item: int(item["sid"]))
    return selected


