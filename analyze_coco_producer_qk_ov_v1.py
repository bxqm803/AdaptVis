def append_jsonl(path: Path, row: Mapping[str, Any]) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(dict(row), ensure_ascii=False) + "\n")


def read_jsonl(path: Path) -> List[Dict[str, Any]]:
    rows: List[Dict[str, Any]] = []
    if not path.exists():
        return rows
    with path.open("r", encoding="utf-8") as handle:
        for line_number, line in enumerate(handle, start=1):
            text = line.strip()
            if not text:
                continue
            try:
                rows.append(json.loads(text))
            except json.JSONDecodeError as exc:
                raise ValueError(f"Invalid JSON at {path}:{line_number}: {exc}") from exc
    return rows


def write_csv(path: Path, rows: Sequence[Mapping[str, Any]]) -> None:
    rows = list(rows)
    path.parent.mkdir(parents=True, exist_ok=True)
    if not rows:
        path.write_text("", encoding="utf-8")
        return
    fields: List[str] = []
    seen = set()
    for row in rows:
        for key in row:
            if key not in seen:
                fields.append(str(key))
                seen.add(key)
    with path.open("w", encoding="utf-8", newline="") as handle:
        writer = csv.DictWriter(handle, fieldnames=fields)
        writer.writeheader()
        for row in rows:
            writer.writerow(dict(row))


def safe_mean(values: Iterable[Any]) -> float:
    array = np.asarray(list(values), dtype=np.float64)
    array = array[np.isfinite(array)]
    return float(array.mean()) if array.size else float("nan")


def safe_median(values: Iterable[Any]) -> float:
    array = np.asarray(list(values), dtype=np.float64)
    array = array[np.isfinite(array)]
    return float(np.median(array)) if array.size else float("nan")


def safe_corr(left: Sequence[Any], right: Sequence[Any]) -> float:
    x = np.asarray(left, dtype=np.float64)
    y = np.asarray(right, dtype=np.float64)
    mask = np.isfinite(x) & np.isfinite(y)
    if int(mask.sum()) < 3:
        return float("nan")
    x = x[mask]
    y = y[mask]
    if float(np.std(x)) < 1e-12 or float(np.std(y)) < 1e-12:
        return float("nan")
    return float(np.corrcoef(x, y)[0, 1])


def macro_accuracy(pred: np.ndarray, labels: np.ndarray) -> float:
    scores = []
    for label in range(len(RELATIONS)):
        mask = labels == label
        if np.any(mask):
            scores.append(float(np.mean(pred[mask] == labels[mask])))
    return safe_mean(scores)


def relation_margin(logits: Sequence[float], gt: str) -> float:
    values = np.asarray(logits, dtype=np.float64)
    return float(
        values[REL_TO_ID[gt]]
        - values[REL_TO_ID[OPPOSITE[gt]]]
    )


def parse_layers(value: str, source_layers: Sequence[int], n_layers: int) -> List[int]:
    text = str(value).strip().lower()
    if text == "source":
        return sorted(set(map(int, source_layers)))
    if text == "all":
        return list(range(n_layers))
    result: List[int] = []
    for item in text.split(","):
        item = item.strip()
        if not item:
            continue
        layer = int(item)
        if not 0 <= layer < n_layers:
            raise ValueError(f"Layer {layer} outside [0,{n_layers - 1}]")
        result.append(layer)
    if not result:
        raise ValueError("No layers selected")
    return sorted(set(result))


def parse_conditions(value: str) -> List[str]:
    conditions = [item.strip() for item in str(value).split(",") if item.strip()]
    invalid = sorted(set(conditions) - set(CAUSAL_CONDITIONS))
    if invalid:
        raise ValueError(
            f"Unsupported causal conditions {invalid}; allowed={CAUSAL_CONDITIONS}"
        )
    if not conditions:
        raise ValueError("No causal conditions selected")
    return list(dict.fromkeys(conditions))


