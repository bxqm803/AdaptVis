@dataclass
class MetricCentroidModel:
    centroids: np.ndarray
    gram: np.ndarray
    metric: str

    def scores(self, x: np.ndarray) -> np.ndarray:
        x = np.asarray(x, dtype=np.float64)
        c = np.asarray(self.centroids, dtype=np.float64)
        gram = np.asarray(self.gram, dtype=np.float64)

        if self.metric == "cosine":
            xg = x @ gram
            numerator = xg @ c.T
            x_norm = np.sqrt(np.clip(np.sum(xg * x, axis=1), 1e-24, None))
            cg = c @ gram
            c_norm = np.sqrt(np.clip(np.sum(cg * c, axis=1), 1e-24, None))
            return numerator / np.clip(x_norm[:, None] * c_norm[None, :], 1e-12, None)

        if self.metric == "euclidean":
            output = np.empty((len(x), len(c)), dtype=np.float64)
            for index, centroid in enumerate(c):
                delta = x - centroid[None, :]
                dg = delta @ gram
                output[:, index] = -np.sqrt(
                    np.clip(np.sum(dg * delta, axis=1), 0.0, None)
                )
            return output

        raise ValueError(self.metric)

    def predict(self, x: np.ndarray) -> np.ndarray:
        return np.argmax(self.scores(x), axis=1).astype(np.int64)

    def gt_opposite_margin(self, x: np.ndarray, labels: np.ndarray) -> np.ndarray:
        scores = self.scores(x)
        result = np.empty((len(x),), dtype=np.float64)
        for index, label in enumerate(labels.tolist()):
            gt = ID_TO_REL[int(label)]
            result[index] = (
                scores[index, int(label)]
                - scores[index, REL_TO_ID[OPPOSITE[gt]]]
            )
        return result


def fit_metric_centroids(
    x: np.ndarray,
    labels: np.ndarray,
    gram: np.ndarray,
    metric: str,
) -> MetricCentroidModel:
    centroids = []
    for relation_id in range(len(RELATIONS)):
        mask = labels == relation_id
        if not np.any(mask):
            raise RuntimeError(
                f"Missing class {ID_TO_REL[relation_id]} in centroid training"
            )
        centroids.append(np.asarray(x[mask], dtype=np.float64).mean(axis=0))
    return MetricCentroidModel(
        centroids=np.stack(centroids, axis=0),
        gram=np.asarray(gram, dtype=np.float64),
        metric=metric,
    )


def crossfit_metric_centroids(
    x: np.ndarray,
    labels: np.ndarray,
    folds: np.ndarray,
    gram: np.ndarray,
    metric: str,
) -> Tuple[np.ndarray, np.ndarray]:
    pred = np.full((len(x),), -1, dtype=np.int64)
    margin = np.full((len(x),), np.nan, dtype=np.float64)
    for fold in sorted(set(folds.tolist())):
        train = folds != fold
        test = folds == fold
        model = fit_metric_centroids(
            x[train],
            labels[train],
            gram,
            metric,
        )
        pred[test] = model.predict(x[test])
        margin[test] = model.gt_opposite_margin(
            x[test],
            labels[test],
        )
    return pred, margin




def crossfit_metric_centroids_batched(
    x: np.ndarray,
    labels: np.ndarray,
    folds: np.ndarray,
    grams: np.ndarray,
    metric: str,
) -> Tuple[np.ndarray, np.ndarray]:
    """Exact cross-fitted centroid classification for all heads in one layer.

    x:     [N,H,Dh]
    grams: [H,Dh,Dh]
    returns prediction/margin with shape [N,H].
    """
    x = np.asarray(x, dtype=np.float64)
    labels = np.asarray(labels, dtype=np.int64)
    folds = np.asarray(folds, dtype=np.int64)
    grams = np.asarray(grams, dtype=np.float64)
    n, n_heads, head_dim = x.shape
    if grams.shape != (n_heads, head_dim, head_dim):
        raise ValueError(
            f"Bad batched Gram shape {grams.shape}; expected "
            f"{(n_heads, head_dim, head_dim)}"
        )

    pred = np.full((n, n_heads), -1, dtype=np.int64)
    margin = np.full((n, n_heads), np.nan, dtype=np.float64)

    for fold in sorted(set(folds.tolist())):
        train = folds != fold
        test = folds == fold
        centroids = np.empty(
            (n_heads, len(RELATIONS), head_dim),
            dtype=np.float64,
        )
        for relation_id in range(len(RELATIONS)):
            mask = train & (labels == relation_id)
            if not np.any(mask):
                raise RuntimeError(
                    f"Fold {fold} misses class {ID_TO_REL[relation_id]}"
                )
            centroids[:, relation_id, :] = x[mask].mean(axis=0)

        xt = x[test]  # [Nt,H,D]
        xg = np.einsum("nhd,hde->nhe", xt, grams, optimize=True)

        if metric == "cosine":
            numerator = np.einsum(
                "nhe,hce->nhc",
                xg,
                centroids,
                optimize=True,
            )
            x_norm = np.sqrt(
                np.clip(
                    np.einsum("nhe,nhe->nh", xg, xt, optimize=True),
                    1e-24,
                    None,
                )
            )
            cg = np.einsum(
                "hcd,hde->hce",
                centroids,
                grams,
                optimize=True,
            )
            c_norm = np.sqrt(
                np.clip(
                    np.einsum(
                        "hce,hce->hc",
                        cg,
                        centroids,
                        optimize=True,
                    ),
                    1e-24,
                    None,
                )
            )
            scores = numerator / np.clip(
                x_norm[:, :, None] * c_norm[None, :, :],
                1e-12,
                None,
            )
        elif metric == "euclidean":
            scores = np.empty(
                (int(test.sum()), n_heads, len(RELATIONS)),
                dtype=np.float64,
            )
            for relation_id in range(len(RELATIONS)):
                delta = xt - centroids[:, relation_id, :][None, :, :]
                dg = np.einsum(
                    "nhd,hde->nhe",
                    delta,
                    grams,
                    optimize=True,
                )
                scores[:, :, relation_id] = -np.sqrt(
                    np.clip(
                        np.einsum(
                            "nhe,nhe->nh",
                            dg,
                            delta,
                            optimize=True,
                        ),
                        0.0,
                        None,
                    )
                )
        else:
            raise ValueError(metric)

        test_indices = np.where(test)[0]
        pred[test_indices] = np.argmax(scores, axis=2)
        for local_index, global_index in enumerate(test_indices.tolist()):
            gt_id = int(labels[global_index])
            opposite_id = REL_TO_ID[OPPOSITE[ID_TO_REL[gt_id]]]
            margin[global_index] = (
                scores[local_index, :, gt_id]
                - scores[local_index, :, opposite_id]
            )

    return pred, margin


def post_wo_norms_batched(x: np.ndarray, grams: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=np.float64)
    grams = np.asarray(grams, dtype=np.float64)
    xg = np.einsum("nhd,hde->nhe", x, grams, optimize=True)
    return np.sqrt(
        np.clip(
            np.einsum("nhe,nhe->nh", xg, x, optimize=True),
            0.0,
            None,
        )
    )

def post_wo_norms(x: np.ndarray, gram: np.ndarray) -> np.ndarray:
    x = np.asarray(x, dtype=np.float64)
    gram = np.asarray(gram, dtype=np.float64)
    xg = x @ gram
    return np.sqrt(np.clip(np.sum(xg * x, axis=1), 0.0, None))


