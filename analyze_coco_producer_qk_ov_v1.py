def load_model_bundle(
    *,
    args: argparse.Namespace,
    base: Any,
) -> Tuple[Any, Any, Any, Sequence[Any], str, Any]:
    two_object = base.import_two_object_module()
    specs = base.merged_model_specs(two_object)
    if args.model not in specs:
        raise ValueError(f"Unknown model {args.model}; available={sorted(specs)}")
    spec = specs[args.model]
    model_class = getattr(transformers, spec.model_class, None)
    if model_class is None:
        raise RuntimeError(
            f"transformers {transformers.__version__} lacks {spec.model_class}"
        )

    kwargs: Dict[str, Any] = {
        "dtype": base.resolve_dtype(spec.dtype_name),
        "low_cpu_mem_usage": True,
        "trust_remote_code": spec.trust_remote_code,
        "device_map": {"": args.device},
        "attn_implementation": args.attn_impl,
    }
    print(f"Loading {args.model}: {spec.repo_id}", flush=True)
    try:
        model = model_class.from_pretrained(spec.repo_id, **kwargs)
    except TypeError:
        kwargs.pop("attn_implementation", None)
        model = model_class.from_pretrained(spec.repo_id, **kwargs)

    model.eval()
    generation_config = getattr(model, "generation_config", None)
    if generation_config is not None:
        if hasattr(generation_config, "do_sample"):
            generation_config.do_sample = False
        for field in ("temperature", "top_p", "top_k"):
            if hasattr(generation_config, field):
                setattr(generation_config, field, None)

    processor = AutoProcessor.from_pretrained(
        spec.repo_id,
        trust_remote_code=spec.trust_remote_code,
    )
    base.configure_processor(model, processor)
    decoder_layers, decoder_path = base.resolve_decoder_layers(model)
    relation_token_map = base.relation_token_variants(processor.tokenizer)
    return model, processor, spec, decoder_layers, decoder_path, relation_token_map


