def main() -> None:
    args = parse_args()
    if args.device.startswith("cuda") and not torch.cuda.is_available():
        raise RuntimeError("CUDA requested but unavailable")
    if args.top_heads < 1:
        raise ValueError("--top-heads must be >= 1")
    if args.trace_layer_chunk < 1:
        raise ValueError("--trace-layer-chunk must be >= 1")

    random.seed(args.seed)
    np.random.seed(args.seed)
    torch.manual_seed(args.seed)

    output_dir = Path(args.output_dir)
    if args.overwrite and output_dir.exists():
        shutil.rmtree(output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    source_dir = Path(args.source_output_dir)
    source_config_path = source_dir / "config.json"
    source_extraction_path = source_dir / "extraction.jsonl"
    if not source_config_path.exists():
        raise FileNotFoundError(source_config_path)
    if not source_extraction_path.exists():
        raise FileNotFoundError(source_extraction_path)

    source_config = json.loads(
        source_config_path.read_text(encoding="utf-8")
    )
    source_rows = read_jsonl(source_extraction_path)
    if args.max_samples is not None:
        source_rows = source_rows[: int(args.max_samples)]
    if not source_rows:
        raise RuntimeError("Source extraction is empty")

    if str(source_config.get("model")) != args.model:
        raise RuntimeError(
            f"Source model={source_config.get('model')} but --model={args.model}"
        )
    if str(source_config.get("dataset")) != args.dataset:
        raise RuntimeError(
            f"Source dataset={source_config.get('dataset')} "
            f"but --dataset={args.dataset}"
        )

    v3 = import_file(Path(args.v3_script), "producer_qk_ov_v3")
    base = import_file(Path(args.base_script), "producer_qk_ov_base")
    attention_helper = import_file(
        Path(args.attention_helper),
        "producer_qk_ov_attention",
    )

    model = None
    processor = None
    scan_rows: List[Dict[str, Any]] = []
    top_rows: List[Dict[str, Any]] = []
    causal_rows: List[Dict[str, Any]] = []

    try:
        (
            model,
            processor,
            spec,
            decoder_layers,
            decoder_path,
            relation_token_map,
        ) = load_model_bundle(args=args, base=base)

        selected_layers = parse_layers(
            args.layers,
            source_config.get("selected_layers", []),
            len(decoder_layers),
        )

        config = {
            "script_version": SCRIPT_VERSION,
            "model": args.model,
            "repo_id": spec.repo_id,
            "dataset": args.dataset,
            "source_output_dir": str(source_dir),
            "source_script_version": source_config.get("script_version"),
            "selected_layers": selected_layers,
            "decoder_path": decoder_path,
            "object_state": args.object_state,
            "centroid_metric": args.centroid_metric,
            "scan_status": args.scan_status,
            "rank_metric": args.rank_metric,
            "top_heads": args.top_heads,
            "causal_status": args.causal_status,
            "causal_max_samples": args.causal_max_samples,
            "causal_conditions": parse_conditions(args.causal_conditions),
            "causal_require_margin_sign": args.causal_require_margin_sign,
            "transformers_version": transformers.__version__,
        }
        write_json(output_dir / "config.json", config)

        if args.phase in {"all", "scan"}:
            selected_scan_rows = [
                row for row in source_rows
                if status_matches(row, args.scan_status)
            ]
            scan = collect_scan_arrays(
                source_dir=source_dir,
                rows=selected_scan_rows,
                selected_layers=selected_layers,
            )
            scan_rows, top_rows = scan_producer_heads(
                args=args,
                v3=v3,
                attention_helper=attention_helper,
                decoder_layers=decoder_layers,
                scan=scan,
                output_dir=output_dir,
            )
        else:
            metrics_path = output_dir / "producer_head_metrics.csv"
            top_path = output_dir / "producer_top_heads.json"
            if not metrics_path.exists() or not top_path.exists():
                raise RuntimeError(
                    "--phase causal requires existing producer scan outputs"
                )
            with metrics_path.open("r", encoding="utf-8") as handle:
                scan_rows = list(csv.DictReader(handle))
            top_rows = json.loads(top_path.read_text(encoding="utf-8"))

        if args.phase in {"all", "causal"}:
            two_object = base.import_two_object_module()
            records, audit = two_object.load_records(
                args.dataset,
                Path(args.data_root),
                args.max_samples,
            )
            records_by_sid = {
                int(record.sid): record for record in records
            }
            prompt_rows = base.load_standard_prompts(
                Path(args.prompt_jsonl)
            )
            causal_rows = run_causal_phase(
                args=args,
                v3=v3,
                base=base,
                attention_helper=attention_helper,
                model=model,
                processor=processor,
                decoder_layers=decoder_layers,
                relation_token_map=relation_token_map,
                source_rows=source_rows,
                records_by_sid=records_by_sid,
                prompt_rows=prompt_rows,
                output_dir=output_dir,
            )

        causal_summary = (
            summarize_causal(causal_rows) if causal_rows else []
        )
        if causal_summary:
            write_csv(
                output_dir / "producer_causal_summary.csv",
                causal_summary,
            )

        write_report(
            output_dir=output_dir,
            args=args,
            scan_rows=scan_rows,
            top_rows=top_rows,
            causal_summary=causal_summary,
        )
        print(f"\nSaved outputs to {output_dir}", flush=True)

    finally:
        if model is not None:
            del model
        if processor is not None:
            del processor
        gc.collect()
        if torch.cuda.is_available():
            torch.cuda.empty_cache()


if __name__ == "__main__":
    main()
