def write_report(
    *,
    output_dir: Path,
    args: argparse.Namespace,
    scan_rows: Sequence[Mapping[str, Any]],
    top_rows: Sequence[Mapping[str, Any]],
    causal_summary: Sequence[Mapping[str, Any]],
) -> None:
    lines = [
        f"script_version: {SCRIPT_VERSION}",
        f"model: {args.model}",
        f"source_output_dir: {args.source_output_dir}",
        "",
    ]

    if scan_rows:
        lines.extend(
            [
                "TOP PRODUCER HEADS",
                (
                    "QK=functional object->visual routing; "
                    "preOV=A·V head-local relation read; "
                    "postOV=W_O(A·V) residual relation write."
                ),
            ]
        )
        for item in top_rows:
            lines.append(
                f"rank={int(item['rank'])} "
                f"L{int(item['layer'])} H{int(item['head'])} "
                f"QK={float(item['qk_attention_centroid_accuracy']):.4f} "
                f"preOV={float(item['pre_ov_centroid_accuracy']):.4f} "
                f"postOV={float(item['post_ov_centroid_accuracy']):.4f} "
                f"mass={float(item['visual_attention_mass_mean']):.6f} "
                f"writeNorm={float(item['post_ov_write_norm_mean']):.6f} "
                f"joint={float(item[args.rank_metric]):.4f}"
            )
        lines.append("")

    if causal_summary:
        lines.append("PRODUCER CAUSAL VALIDATION")
        ranked = sorted(
            causal_summary,
            key=lambda row: float(row["mean_normalized_effect"]),
            reverse=True,
        )
        for row in ranked[:40]:
            lines.append(
                f"{row['unit']} L{int(row['layer'])} "
                f"{row['condition']} N={int(row['N'])} "
                f"effect={float(row['mean_normalized_effect']):+.6f} "
                f"raw={float(row['mean_raw_effect']):+.6f} "
                f"positive={float(row['positive_effect_rate']):.4f} "
                f"crossed={float(row['crossed_decision_boundary_rate']):.4f} "
                f"replayOK={float(row['replay_within_tolerance_rate']):.4f}"
            )
        lines.extend(
            [
                "",
                "Interpretation:",
                "  qk_swap_on_original / qk_restore_on_swapped isolate the",
                "  selected head's object->visual routing pattern while holding",
                "  the target run's visual V states fixed.",
                "  ov_visual_ablate_on_original removes the selected head's",
                "  actual post-W_O visual write at object tokens.",
                "  full_visual_write_restore_on_swapped restores the complete",
                "  A·V·W_O producer contribution and is a sufficiency test.",
                "  These results identify producer heads. They do not yet identify",
                "  the downstream receiver Q/K/V composition path.",
            ]
        )

    (output_dir / "report.txt").write_text(
        "\n".join(lines) + "\n",
        encoding="utf-8",
    )


