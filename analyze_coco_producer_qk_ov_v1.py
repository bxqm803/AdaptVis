class AttentionTargetDelta:
    """Add residual-space deltas to selected token rows of attention output."""

    def __init__(
        self,
        attention_module: torch.nn.Module,
        position_to_delta: Mapping[int, np.ndarray],
    ):
        self.position_to_delta = {
            int(position): np.asarray(delta, dtype=np.float32)
            for position, delta in position_to_delta.items()
        }
        self.applied = False
        self.handle = attention_module.register_forward_hook(self._hook)

    def _hook(self, module: Any, inputs: Tuple[Any, ...], output: Any) -> Any:
        hidden = first_tensor(output)
        modified = hidden.clone()
        applied = 0
        for position, delta_np in self.position_to_delta.items():
            if not 0 <= position < int(hidden.shape[1]):
                raise RuntimeError(
                    f"Intervention position {position} outside sequence length "
                    f"{int(hidden.shape[1])}"
                )
            delta = torch.as_tensor(
                delta_np,
                device=hidden.device,
                dtype=hidden.dtype,
            )
            modified[:, position, :] = modified[:, position, :] + delta
            applied += 1
        self.applied = applied > 0
        return replace_first_tensor(output, modified)

    def close(self) -> None:
        with contextlib.suppress(Exception):
            self.handle.remove()

    def __enter__(self) -> "AttentionTargetDelta":
        return self

    def __exit__(self, exc_type: Any, exc: Any, tb: Any) -> None:
        self.close()


def first_tensor(output: Any) -> torch.Tensor:
    if torch.is_tensor(output):
        return output
    if isinstance(output, (tuple, list)):
        for value in output:
            if torch.is_tensor(value) and value.ndim == 3:
                return value
    for name in ("last_hidden_state", "hidden_states"):
        value = getattr(output, name, None)
        if torch.is_tensor(value) and value.ndim == 3:
            return value
    raise TypeError(f"Cannot locate 3D tensor in {type(output).__name__}")


def replace_first_tensor(output: Any, modified: torch.Tensor) -> Any:
    if torch.is_tensor(output):
        return modified
    if isinstance(output, tuple):
        values = list(output)
        for index, value in enumerate(values):
            if torch.is_tensor(value) and value.ndim == 3:
                values[index] = modified
                return tuple(values)
    if isinstance(output, list):
        values = list(output)
        for index, value in enumerate(values):
            if torch.is_tensor(value) and value.ndim == 3:
                values[index] = modified
                return values
    raise TypeError(f"Cannot replace 3D tensor in {type(output).__name__}")


def target_local_index(trace: Any, position: int) -> int:
    lookup = {
        int(global_position): local
        for local, global_position in enumerate(trace.target_positions)
    }
    if int(position) not in lookup:
        raise KeyError(
            f"Target position {position} absent from trace targets "
            f"{trace.target_positions}"
        )
    return int(lookup[int(position)])


def visual_pre_vector(
    *,
    trace: Any,
    head: int,
    target_position: int,
    visual_positions: Sequence[int],
    routing_trace: Optional[Any] = None,
    routing_target_position: Optional[int] = None,
    value_trace: Optional[Any] = None,
) -> torch.Tensor:
    routing = routing_trace if routing_trace is not None else trace
    values_source = value_trace if value_trace is not None else trace
    routing_target = (
        int(routing_target_position)
        if routing_target_position is not None
        else int(target_position)
    )
    local = target_local_index(routing, routing_target)
    visual = torch.as_tensor(
        list(map(int, visual_positions)),
        dtype=torch.long,
    )
    weights = routing.attention_weights[int(head), local].index_select(
        0,
        visual,
    ).float()
    values = values_source.value_states[int(head)].index_select(
        0,
        visual,
    ).float()
    return torch.einsum("s,sd->d", weights, values)


def project_one_head(
    trace: Any,
    head: int,
    pre_vector: torch.Tensor,
) -> torch.Tensor:
    weight = trace.o_proj_weight[:, int(head), :].float()
    return torch.einsum("d,od->o", pre_vector.float(), weight)


def aligned_position_pairs(
    original_positions: Sequence[int],
    swapped_positions: Sequence[int],
) -> List[Tuple[int, int]]:
    original = list(map(int, original_positions))
    swapped = list(map(int, swapped_positions))
    if len(original) != len(swapped):
        raise RuntimeError(
            f"Identity-aligned object token lengths differ: "
            f"{len(original)} vs {len(swapped)}"
        )
    return list(zip(original, swapped))


def build_condition_deltas(
    *,
    condition: str,
    heads: Sequence[int],
    original_trace: Any,
    swapped_trace: Any,
    original_a_positions: Sequence[int],
    original_b_positions: Sequence[int],
    swapped_a_positions: Sequence[int],
    swapped_b_positions: Sequence[int],
    visual_positions_original: Sequence[int],
    visual_positions_swapped: Sequence[int],
) -> Tuple[str, Dict[int, np.ndarray]]:
    if list(map(int, visual_positions_original)) != list(map(int, visual_positions_swapped)):
        raise RuntimeError(
            "Original/swapped visual token positions differ; QK routing replacement "
            "requires aligned visual source positions."
        )

    identity_pairs = (
        aligned_position_pairs(original_a_positions, swapped_a_positions)
        + aligned_position_pairs(original_b_positions, swapped_b_positions)
    )

    target_side = (
        "original"
        if condition in {
            "qk_swap_on_original",
            "ov_visual_ablate_on_original",
        }
        else "swapped"
    )
    deltas: Dict[int, torch.Tensor] = {}

    for original_position, swapped_position in identity_pairs:
        target_position = (
            original_position if target_side == "original" else swapped_position
        )
        total = None

        for head in heads:
            original_full = visual_pre_vector(
                trace=original_trace,
                head=head,
                target_position=original_position,
                visual_positions=visual_positions_original,
            )
            swapped_full = visual_pre_vector(
                trace=swapped_trace,
                head=head,
                target_position=swapped_position,
                visual_positions=visual_positions_swapped,
            )

            if condition == "qk_swap_on_original":
                routed = visual_pre_vector(
                    trace=original_trace,
                    head=head,
                    target_position=original_position,
                    visual_positions=visual_positions_original,
                    routing_trace=swapped_trace,
                    routing_target_position=swapped_position,
                    value_trace=original_trace,
                )
                delta_head = project_one_head(
                    original_trace,
                    head,
                    routed - original_full,
                )

            elif condition == "ov_visual_ablate_on_original":
                delta_head = -project_one_head(
                    original_trace,
                    head,
                    original_full,
                )

            elif condition == "qk_restore_on_swapped":
                routed = visual_pre_vector(
                    trace=swapped_trace,
                    head=head,
                    target_position=swapped_position,
                    visual_positions=visual_positions_swapped,
                    routing_trace=original_trace,
                    routing_target_position=original_position,
                    value_trace=swapped_trace,
                )
                delta_head = project_one_head(
                    swapped_trace,
                    head,
                    routed - swapped_full,
                )

            elif condition == "full_visual_write_restore_on_swapped":
                original_write = project_one_head(
                    original_trace,
                    head,
                    original_full,
                )
                swapped_write = project_one_head(
                    swapped_trace,
                    head,
                    swapped_full,
                )
                delta_head = original_write - swapped_write

            else:
                raise ValueError(condition)

            total = delta_head if total is None else total + delta_head

        if total is None:
            raise RuntimeError("No heads supplied to intervention")
        if target_position in deltas:
            deltas[target_position] = deltas[target_position] + total
        else:
            deltas[target_position] = total

    return target_side, {
        int(position): tensor.detach().float().cpu().numpy()
        for position, tensor in deltas.items()
    }


@torch.inference_mode()
def run_margin(
    *,
    model: Any,
    base: Any,
    relation_token_map: Mapping[str, Sequence[int]],
    batch: Mapping[str, Any],
    gt_original_axis: str,
    attention_module: Optional[torch.nn.Module] = None,
    deltas: Optional[Mapping[int, np.ndarray]] = None,
) -> Dict[str, Any]:
    intervention: Optional[AttentionTargetDelta] = None
    try:
        if attention_module is not None:
            if not deltas:
                raise ValueError("attention_module provided without deltas")
            intervention = AttentionTargetDelta(
                attention_module,
                deltas,
            )
        outputs = model(
            **batch,
            use_cache=False,
            return_dict=True,
        )
        if intervention is not None and not intervention.applied:
            raise RuntimeError("Attention intervention hook did not fire")
        relation = base.relation_scores(
            outputs.logits[0, -1],
            dict(relation_token_map),
            gt=None,
        )
        logits = np.asarray(relation["logits"], dtype=np.float64)
        return {
            "logits": logits.tolist(),
            "prediction": str(relation["prediction"]),
            "margin": relation_margin(logits, gt_original_axis),
        }
    finally:
        if intervention is not None:
            intervention.close()
        with contextlib.suppress(Exception):
            del outputs


def parse_causal_heads(
    value: str,
    top_path: Path,
) -> List[Tuple[int, int]]:
    text = str(value).strip().lower()
    if text == "top":
        if not top_path.exists():
            raise FileNotFoundError(top_path)
        values = json.loads(top_path.read_text(encoding="utf-8"))
        return [
            (int(item["layer"]), int(item["head"]))
            for item in values
        ]

    result = []
    for item in str(value).split(","):
        item = item.strip()
        if not item:
            continue
        layer_text, head_text = item.split(":", 1)
        result.append((int(layer_text), int(head_text)))
    if not result:
        raise ValueError("No causal heads selected")
    return list(dict.fromkeys(result))


def causal_units(
    selected_heads: Sequence[Tuple[int, int]],
    include_unions: bool,
) -> List[Dict[str, Any]]:
    units: List[Dict[str, Any]] = []
    for rank, (layer, head) in enumerate(selected_heads, start=1):
        units.append(
            {
                "unit": f"top_rank_{rank}",
                "layer": int(layer),
                "heads": [int(head)],
            }
        )

    if include_unions:
        grouped: Dict[int, List[int]] = defaultdict(list)
        for layer, head in selected_heads:
            grouped[int(layer)].append(int(head))
        for layer, heads in sorted(grouped.items()):
            unique = sorted(set(heads))
            if len(unique) > 1:
                units.append(
                    {
                        "unit": f"top_union_L{layer}",
                        "layer": int(layer),
                        "heads": unique,
                    }
                )
    return units


def run_causal_phase(
    *,
    args: argparse.Namespace,
    v3: Any,
    base: Any,
    attention_helper: Any,
    model: Any,
    processor: Any,
    decoder_layers: Sequence[Any],
    relation_token_map: Mapping[str, Sequence[int]],
    source_rows: Sequence[Mapping[str, Any]],
    records_by_sid: Mapping[int, Any],
    prompt_rows: Mapping[int, Mapping[str, Any]],
    output_dir: Path,
) -> List[Dict[str, Any]]:
    selected_heads = parse_causal_heads(
        args.causal_heads,
        output_dir / "producer_top_heads.json",
    )
    units = causal_units(
        selected_heads,
        args.causal_layer_unions,
    )
    selected_layers = sorted({int(unit["layer"]) for unit in units})
    conditions = parse_conditions(args.causal_conditions)

    eligible = [
        dict(row) for row in source_rows
        if status_matches(row, args.causal_status)
    ]
    filtered: List[Dict[str, Any]] = []
    for row in eligible:
        original_cached_margin = float(row["baseline_lm_margin"])
        swapped_cached_margin = relation_margin(
            row["swapped_relation_logits"],
            str(row["gt"]),
        )
        if abs(original_cached_margin - swapped_cached_margin) < args.min_margin_denominator:
            continue
        if args.causal_require_margin_sign and not (
            original_cached_margin > 0 and swapped_cached_margin < 0
        ):
            continue
        filtered.append(row)
    eligible = filtered
    eligible = stratified_limit(
        eligible,
        args.causal_max_samples,
        args.seed,
    )
    if not eligible:
        raise RuntimeError("No samples eligible for producer causal validation")

    print(
        f"Producer causal: N={len(eligible)}, layers={selected_layers}, "
        f"units={len(units)}, conditions={conditions}",
        flush=True,
    )

    output_path = output_dir / "producer_causal.jsonl"
    errors_path = output_dir / "errors.jsonl"
    existing = read_jsonl(output_path) if args.resume else []
    completed = {
        (
            int(row["sid"]),
            str(row["unit"]),
            str(row["condition"]),
        )
        for row in existing
    }

    rows = list(existing)
    device = torch.device(args.device)
    processed_samples = 0

    for row in tqdm(eligible, desc=f"producer-causal:{args.model}"):
        sid = int(row["sid"])
        image: Optional[Image.Image] = None
        original_batch: Optional[Dict[str, Any]] = None
        swapped_batch: Optional[Dict[str, Any]] = None

        try:
            prompt = prompt_rows[sid]
            subject = str(prompt["subject"])
            reference = str(prompt["reference"])
            original_question = str(prompt["question_text"])
            swapped_question = base.build_swapped_question(subject, reference)
            gt = str(row["gt"])
            swapped_gt = OPPOSITE[gt]

            image = base.record_image(records_by_sid[sid])
            original_batch = base.make_question_batch(
                processor=processor,
                image=image,
                question_text=original_question,
                device=device,
            )
            swapped_batch = base.make_question_batch(
                processor=processor,
                image=image,
                question_text=swapped_question,
                device=device,
            )

            original_ids = original_batch["input_ids"][0].detach().cpu().tolist()
            swapped_ids = swapped_batch["input_ids"][0].detach().cpu().tolist()

            original_a_span, original_b_span = base.locate_object_spans(
                processor.tokenizer,
                original_ids,
                subject,
                reference,
            )
            swapped_b_span, swapped_a_span = base.locate_object_spans(
                processor.tokenizer,
                swapped_ids,
                reference,
                subject,
            )

            original_a_positions = v3.span_positions(
                original_a_span,
                args.object_state,
            )
            original_b_positions = v3.span_positions(
                original_b_span,
                args.object_state,
            )
            swapped_a_positions = v3.span_positions(
                swapped_a_span,
                args.object_state,
            )
            swapped_b_positions = v3.span_positions(
                swapped_b_span,
                args.object_state,
            )

            original_targets = sorted(
                set(original_a_positions + original_b_positions)
            )
            swapped_targets = sorted(
                set(swapped_a_positions + swapped_b_positions)
            )

            original_visual = base.resolve_visual_indices(
                model,
                processor,
                dict(original_batch),
                original_ids,
            )
            swapped_visual = base.resolve_visual_indices(
                model,
                processor,
                dict(swapped_batch),
                swapped_ids,
            )

            original_baseline, original_traces = v3.trace_prompt_chunks(
                attention_helper=attention_helper,
                model=model,
                batch=original_batch,
                relation_token_map=relation_token_map,
                decoder_layers=decoder_layers,
                layers=selected_layers,
                target_positions=original_targets,
                chunk_size=args.trace_layer_chunk,
            )
            swapped_baseline, swapped_traces = v3.trace_prompt_chunks(
                attention_helper=attention_helper,
                model=model,
                batch=swapped_batch,
                relation_token_map=relation_token_map,
                decoder_layers=decoder_layers,
                layers=selected_layers,
                target_positions=swapped_targets,
                chunk_size=args.trace_layer_chunk,
            )

            original_margin = relation_margin(
                [original_baseline["scores"][relation] for relation in RELATIONS],
                gt,
            )
            swapped_margin = relation_margin(
                [swapped_baseline["scores"][relation] for relation in RELATIONS],
                gt,
            )
            denominator = float(original_margin - swapped_margin)
            if abs(denominator) < args.min_margin_denominator:
                continue
            if args.causal_require_margin_sign and not (
                original_margin > 0 and swapped_margin < 0
            ):
                continue

            max_replay_error = max(
                [
                    float(original_traces[layer].replay_relative_error)
                    for layer in selected_layers
                ]
                + [
                    float(swapped_traces[layer].replay_relative_error)
                    for layer in selected_layers
                ]
            )

            for unit in units:
                layer = int(unit["layer"])
                heads = list(map(int, unit["heads"]))
                attention_module = attention_helper.resolve_self_attention(
                    decoder_layers[layer]
                )

                for condition in conditions:
                    key = (sid, str(unit["unit"]), condition)
                    if key in completed:
                        continue
                    try:
                        target_side, deltas = build_condition_deltas(
                            condition=condition,
                            heads=heads,
                            original_trace=original_traces[layer],
                            swapped_trace=swapped_traces[layer],
                            original_a_positions=original_a_positions,
                            original_b_positions=original_b_positions,
                            swapped_a_positions=swapped_a_positions,
                            swapped_b_positions=swapped_b_positions,
                            visual_positions_original=original_visual,
                            visual_positions_swapped=swapped_visual,
                        )
                        target_batch = (
                            original_batch
                            if target_side == "original"
                            else swapped_batch
                        )
                        intervention = run_margin(
                            model=model,
                            base=base,
                            relation_token_map=relation_token_map,
                            batch=target_batch,
                            gt_original_axis=gt,
                            attention_module=attention_module,
                            deltas=deltas,
                        )
                        intervened_margin = float(intervention["margin"])

                        if target_side == "original":
                            raw_effect = float(original_margin - intervened_margin)
                            normalized_effect = float(raw_effect / denominator)
                            expected_positive = raw_effect > 0
                            crossed = intervened_margin < 0
                            metric_name = "normalized_damage"
                        else:
                            raw_effect = float(intervened_margin - swapped_margin)
                            normalized_effect = float(raw_effect / denominator)
                            expected_positive = raw_effect > 0
                            crossed = intervened_margin > 0
                            metric_name = "normalized_recovery"

                        result = {
                            "script_version": SCRIPT_VERSION,
                            "model": args.model,
                            "sid": sid,
                            "gt": gt,
                            "swapped_gt": swapped_gt,
                            "generation_pair_status": row["generation_pair_status"],
                            "unit": str(unit["unit"]),
                            "layer": layer,
                            "heads": heads,
                            "condition": condition,
                            "target_side": target_side,
                            "original_margin": float(original_margin),
                            "swapped_margin_fixed_axis": float(swapped_margin),
                            "intervened_margin_fixed_axis": intervened_margin,
                            "margin_denominator": denominator,
                            "raw_effect": raw_effect,
                            "normalized_effect": normalized_effect,
                            "normalized_metric": metric_name,
                            "expected_positive": bool(expected_positive),
                            "crossed_decision_boundary": bool(crossed),
                            "intervened_prediction": intervention["prediction"],
                            "max_replay_relative_error": max_replay_error,
                            "replay_within_tolerance": bool(
                                max_replay_error <= args.replay_tolerance
                            ),
                        }
                        append_jsonl(output_path, result)
                        rows.append(result)
                        completed.add(key)
                    except Exception as exc:
                        append_jsonl(
                            errors_path,
                            {
                                "phase": "causal",
                                "sid": sid,
                                "unit": unit["unit"],
                                "layer": layer,
                                "heads": heads,
                                "condition": condition,
                                "error_type": type(exc).__name__,
                                "error": str(exc),
                                "traceback": traceback.format_exc(),
                            },
                        )
                        print(
                            f"\n[ERROR causal sid={sid} {unit['unit']} "
                            f"{condition}] {type(exc).__name__}: {exc}",
                            flush=True,
                        )
                        if args.fail_fast:
                            raise

            processed_samples += 1
            if args.print_every > 0 and processed_samples % args.print_every == 0:
                print(
                    f"[causal {processed_samples}/{len(eligible)}] sid={sid} "
                    f"gt={gt} M_orig={original_margin:+.5f} "
                    f"M_swap={swapped_margin:+.5f} "
                    f"replay={max_replay_error:.3e}",
                    flush=True,
                )

        except Exception as exc:
            append_jsonl(
                errors_path,
                {
                    "phase": "sample_setup",
                    "sid": sid,
                    "error_type": type(exc).__name__,
                    "error": str(exc),
                    "traceback": traceback.format_exc(),
                },
            )
            print(
                f"\n[ERROR sample sid={sid}] {type(exc).__name__}: {exc}",
                flush=True,
            )
            if args.fail_fast:
                raise
        finally:
            if image is not None:
                with contextlib.suppress(Exception):
                    image.close()
            if original_batch is not None:
                del original_batch
            if swapped_batch is not None:
                del swapped_batch
            gc.collect()
            if torch.cuda.is_available() and (
                args.empty_cache_every <= 1
                or max(processed_samples, 1) % args.empty_cache_every == 0
            ):
                torch.cuda.empty_cache()

    rows.sort(
        key=lambda item: (
            str(item["unit"]),
            str(item["condition"]),
            int(item["sid"]),
        )
    )
    output_path.unlink(missing_ok=True)
    for result in rows:
        append_jsonl(output_path, result)

    summary = summarize_causal(rows)
    write_csv(output_dir / "producer_causal_summary.csv", summary)
    return rows


def summarize_causal(rows: Sequence[Mapping[str, Any]]) -> List[Dict[str, Any]]:
    groups: Dict[Tuple[str, int, str], List[Mapping[str, Any]]] = defaultdict(list)
    for row in rows:
        groups[
            (
                str(row["unit"]),
                int(row["layer"]),
                str(row["condition"]),
            )
        ].append(row)

    summary: List[Dict[str, Any]] = []
    for (unit, layer, condition), values in sorted(groups.items()):
        summary.append(
            {
                "unit": unit,
                "layer": layer,
                "condition": condition,
                "heads": json.dumps(values[0]["heads"]),
                "N": len(values),
                "mean_raw_effect": safe_mean(
                    row["raw_effect"] for row in values
                ),
                "median_raw_effect": safe_median(
                    row["raw_effect"] for row in values
                ),
                "mean_normalized_effect": safe_mean(
                    row["normalized_effect"] for row in values
                ),
                "median_normalized_effect": safe_median(
                    row["normalized_effect"] for row in values
                ),
                "positive_effect_rate": safe_mean(
                    int(bool(row["expected_positive"])) for row in values
                ),
                "crossed_decision_boundary_rate": safe_mean(
                    int(bool(row["crossed_decision_boundary"])) for row in values
                ),
                "replay_within_tolerance_rate": safe_mean(
                    int(bool(row["replay_within_tolerance"])) for row in values
                ),
            }
        )
    return summary


